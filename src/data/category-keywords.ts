/** Strong search keywords for a category — curated first, then generated. */
export function getCategorySearchKeywords(
  categoryId: string,
  limit = 15,
): string[] {
  const id = categoryId.trim().toLowerCase();
  const curated = CATEGORY_POWER_KEYWORDS[id];
  if (curated?.length) {
    return curated.slice(0, limit);
  }

  const cat = findCategory(id);
  if (!cat) return [];

  const base = cat.query.trim();
  const generated = [
    base,
    ...PROBLEM_SUFFIXES.map((s) => `${base} ${s}`),
    ...PROBLEM_SUFFIXES.slice(0, 6).map((s) => `${s} ${base}`),
    ...TREND_SUFFIXES.map((s) => `${base} ${s}`),
  ];

  return [...new Set(generated.map((q) => q.trim()).filter((q) => q.length >= 3))].slice(
    0,
    limit,
  );
}

/** Primary + fallback keywords for multi-query search (deduped). */
export function buildSearchKeywordChain(
  primaryQuery: string,
  categoryId?: string,
  limit = 8,
): string[] {
  const primary = primaryQuery.trim();
  const chain: string[] = [];

  if (primary.length >= 2) chain.push(primary);

  if (categoryId) {
    for (const kw of getCategorySearchKeywords(categoryId, limit)) {
      if (!chain.some((q) => q.toLowerCase() === kw.toLowerCase())) {
        chain.push(kw);
      }
    }
  }

  return chain.slice(0, limit);
}
